#!/usr/bin/env bash
# Regenerate every launcher icon from scripts/app_icon/stringlings_icon.mjs.
#
#   bash scripts/gen_app_icons.sh
#
# Renders the 1024 px artwork with headless Chrome, then scales it with sips:
#   iOS     ios/Runner/Assets.xcassets/AppIcon.appiconset/ (every size in its
#           Contents.json; opaque — App Store Connect rejects an icon with alpha)
#   Android mipmap-*/ic_launcher.png (legacy, full artwork) and the adaptive
#           pair ic_launcher_foreground / ic_launcher_background, wired up by
#           mipmap-anydpi-v26/ic_launcher.xml
#   Launch  the icon as a shadowed tile: ios LaunchImage.imageset and Android
#           drawable-*/launch_image.png
#   Dart    lib/ui/splash/stringlings_art.g.dart, the eyeless icon plus eye
#           geometry, which the launch splash uses to blink
set -euo pipefail
cd "$(dirname "$0")/.."

CHROME="/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
[[ -x "$CHROME" ]] || { echo "needs Google Chrome at $CHROME" >&2; exit 1; }
GEN=scripts/app_icon/stringlings_icon.mjs
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

render() { # variant [css px] [device scale] → $TMP/<variant>.png
  local px=${2:-1024} scale=${3:-1}
  node "$GEN" "$1" > "$TMP/$1.html"
  "$CHROME" --headless=new --disable-gpu --hide-scrollbars --force-device-scale-factor="$scale" \
    --default-background-color=00000000 --window-size="$px,$px" \
    --screenshot="$TMP/$1.png" "file://$TMP/$1.html" >/dev/null 2>&1
  local want=$((px * scale))
  [[ "$(sips -g pixelWidth "$TMP/$1.png" | awk '/pixelWidth/{print $2}')" == "$want" ]] \
    || { echo "render of $1 is not $want px wide" >&2; exit 1; }
}
render full; render fg; render bg
render launch 200 4   # 200 pt box at 4x = 800 px, scaled down per density below

# Flatten the full artwork: a BMP round trip drops the alpha channel.
sips -s format bmp "$TMP/full.png" --out "$TMP/full.bmp" >/dev/null
sips -s format png "$TMP/full.bmp" --out "$TMP/full_opaque.png" >/dev/null
[[ "$(sips -g hasAlpha "$TMP/full_opaque.png" | awk '/hasAlpha/{print $2}')" == no ]] \
  || { echo "could not remove alpha from the iOS artwork" >&2; exit 1; }

resize() { sips -z "$2" "$2" "$1" --out "$3" >/dev/null; }

# iOS: one PNG per entry in Contents.json, at size × scale pixels.
SET=ios/Runner/Assets.xcassets/AppIcon.appiconset
python3 - "$SET/Contents.json" <<'EOF' | while read -r px file; do
import json, sys
for i in json.load(open(sys.argv[1]))['images']:
    if 'filename' in i:
        w = float(i['size'].split('x')[0]) * float(i['scale'].rstrip('x'))
        print(int(round(w)), i['filename'])
EOF
  resize "$TMP/full_opaque.png" "$px" "$SET/$file"
  echo "ios  $px  $file"
done

# Android: legacy 48 dp, adaptive layers 108 dp.
RES=android/app/src/main/res
for d in mdpi:1 hdpi:1.5 xhdpi:2 xxhdpi:3 xxxhdpi:4; do
  name=${d%%:*}; k=${d##*:}
  legacy=$(python3 -c "print(round(48*$k))"); layer=$(python3 -c "print(round(108*$k))")
  mkdir -p "$RES/mipmap-$name"
  resize "$TMP/full_opaque.png" "$legacy" "$RES/mipmap-$name/ic_launcher.png"
  resize "$TMP/fg.png" "$layer" "$RES/mipmap-$name/ic_launcher_foreground.png"
  resize "$TMP/bg.png" "$layer" "$RES/mipmap-$name/ic_launcher_background.png"
  echo "android  $name  $legacy / $layer"
done
mkdir -p "$RES/mipmap-anydpi-v26"
cat > "$RES/mipmap-anydpi-v26/ic_launcher.xml" <<'EOF'
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/gen_app_icons.sh -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@mipmap/ic_launcher_background"/>
    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>
</adaptive-icon>
EOF
# Launch image: 200 pt box holding the 160 pt tile (see LAUNCH_PT in the .mjs).
LI=ios/Runner/Assets.xcassets/LaunchImage.imageset
resize "$TMP/launch.png" 200 "$LI/LaunchImage.png"
resize "$TMP/launch.png" 400 "$LI/LaunchImage@2x.png"
resize "$TMP/launch.png" 600 "$LI/LaunchImage@3x.png"
for d in mdpi:1 hdpi:1.5 xhdpi:2 xxhdpi:3 xxxhdpi:4; do
  name=${d%%:*}; k=${d##*:}
  mkdir -p "$RES/drawable-$name"
  resize "$TMP/launch.png" "$(python3 -c "print(round(200*$k))")" "$RES/drawable-$name/launch_image.png"
done
echo "launch images"

mkdir -p lib/ui/splash
node "$GEN" dart > lib/ui/splash/stringlings_art.g.dart
echo "lib/ui/splash/stringlings_art.g.dart"
echo "done"
